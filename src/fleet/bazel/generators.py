"""`BUILD.bazel` and `MODULE.bazel` text generation, and MVS version reconciliation (§3.3).

Pure: data in, text out. Nothing here shells out, reads a file, or needs `bazel` on `PATH` —
which is what lets Phase 3's whole emission layer be tested offline, and what makes the
"generated BUILD files are byte-identical across processes" property (§11.6) checkable rather
than aspirational. Every ordering below is an explicit `sorted(...)`; not one of them is "the
order the dict happened to be in", because a `dict` populated from a `set` re-orders under a
different `PYTHONHASHSEED` and would rewrite the whole monorepo on the next run.

**Version reconciliation is real MVS, not a vote.** Each requirement is recorded as a
`bazel_dep`, and the selected version is the **minimum version satisfying ALL specs** — exactly
what Bazel's Minimal Version Selection computes as the maximum of the declared lower bounds,
checked against every declared upper bound. The rule this replaces was "the highest version
satisfying the most specs", which is a plurality vote wearing MVS's name: with 30 repos pinned
`[31, 32)` and 31 repos pinned `[33, 34)` it selects 33 and ships a build that violates 30
repos' declared upper bound, silently. Here that spec set has an **empty intersection**, so it
raises `VersionConflict` at `severity='error'` and *only then* is the `conflict_resolution` role
(§7.7) allowed an opinion — whose proposal `validate_override` re-derives against every
contributing spec before a line of it is written. The model may choose which promise to break;
it may not tell us which promises it kept.
"""

