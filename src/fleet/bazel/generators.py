def _render_scalar(value: str | int | bool) -> str:
    """Starlark's scalar syntax is JSON's for exactly these three types, and `json.dumps` is the
    escaper we do not have to get right ourselves for a path containing a quote."""
    if isinstance(value, bool):  # before int: bool IS an int in Python, and `True` != `1` here
        return "True" if value else "False"
    if isinstance(value, int):
        return str(value)
    return json.dumps(value)


def _render_attr(name: str, value: str | int | bool | Sequence[str]) -> list[str]:
    if isinstance(value, str | int | bool):
        return [f"{_INDENT}{name} = {_render_scalar(value)},"]
    lines = [f"{_INDENT}{name} = ["]
    lines += [f"{_INDENT * 2}{_render_scalar(item)}," for item in value]
    lines.append(f"{_INDENT}],")
    return lines


def render_target(target: BuildTarget) -> str:
    """One rule instance, in a fixed attribute order.

    Empty lists are omitted rather than rendered as `[]`: an adapter that returns no `deps` and
    an adapter that returns `deps = []` must produce the same bytes, or a no-op adapter change
    shows up as a diff on 250 BUILD files.
    """
    lines = [f"{target.rule}("]
    lines += _render_attr("name", target.name)
    if target.srcs:
        lines += _render_attr("srcs", target.srcs)
    if target.deps:
        lines += _render_attr("deps", sorted(set(target.deps)))
    for key in sorted(target.attrs):
        lines += _render_attr(key, target.attrs[key])
    if target.testonly:
        lines += _render_attr("testonly", True)
    if target.visibility:
        lines += _render_attr("visibility", target.visibility)
    lines.append(")")
    return "\n".join(lines)


def _load_statements(targets: Iterable[BuildTarget]) -> list[str]:
    by_bzl: dict[str, set[str]] = {}
    for target in targets:
        if target.load_from is not None:
            by_bzl.setdefault(target.load_from, set()).add(target.rule)
    return [
        "load("
        + ", ".join([_render_scalar(bzl)] + [_render_scalar(s) for s in sorted(by_bzl[bzl])])
        + ")"
        for bzl in sorted(by_bzl)
    ]


def render_build_bazel(targets: Sequence[BuildTarget], *, header: str = GENERATED_HEADER) -> str:
    """A whole `BUILD.bazel`, deterministic and byte-stable for a given target list.

    Targets are sorted by `(name, rule)` and loads by `.bzl` label, so two runs over the same
    plan — in different processes, under different hash seeds — produce identical bytes and the
    integration branch shows a diff only where the *inputs* changed.
    """
    packages = {t.package for t in targets}
    if len(packages) > 1:
        raise ValueError(
            f"render_build_bazel got targets from {len(packages)} packages "
            f"({', '.join(sorted(packages))}); one BUILD file describes exactly one package"
        )
    ordered = sorted(targets, key=lambda t: (t.name, t.rule))
    blocks = _load_statements(ordered)
    body = [render_target(t) for t in ordered]
    chunks = [header.rstrip("\n")]
    if blocks:
        chunks.append("\n".join(blocks))
    chunks.extend(body)
    return "\n\n".join(chunks) + "\n"


def render_root_package(
    paths: Sequence[str],
    *,
    targets: Sequence[BuildTarget] = (),
    header: str = GENERATED_HEADER,
) -> str:
    """The monorepo root's `BUILD.bazel`, exporting every root file a MODULE.bazel tag NAMES.

    **`//:requirements.lock` is a LABEL, and a label needs a package.** Materialising the file
    (D10) was only half the contract: with no `BUILD.bazel` at the monorepo root the root is not
    a Bazel package at all, and real Bazel answers `Error in read: Unable to load package for
    //:requirements.lock: BUILD file not found in any of the following directories`, from inside
    `rules_python`'s `parse_requirements.bzl`, for a file that is sitting right there on disk.
    The same sentence is owed to `npm_translate_lock`'s `//:pnpm-lock.yaml` and
    `//:.bazelignore`, and to `crate.from_cargo`'s `//:Cargo.lock`.

    Exported explicitly rather than by `glob(["*"])`: the export list is then exactly the set of
    files some adapter declared, so a root file that stops being declared stops being exported
    and the monorepo root never accumulates a public surface nobody asked for.

    `targets` are the RULES an adapter needs in this package — `root_targets()`, which today is
    rules_js's `npm_link_all_packages()` and the only reason the pnpm virtual store that every
    `node_modules/<pkg>` link resolves through exists at all.
    Taken as data, so this module still knows no language: it renders whatever loads and rules it
    is handed, sorted, and a target whose `package` is not the root is a caller error rather than
    a file that quietly declares a rule in the wrong place.
    """
    misplaced = sorted({t.package for t in targets if t.package.strip("/")})
    if misplaced:
        raise ValueError(
            f"render_root_package got targets from {misplaced}; the root package is '' and a "
            f"target declared here would be addressed as //:<name> whatever its package says"
        )
    ordered = sorted(targets, key=lambda t: (t.name, t.rule))
    exported = "".join(f"{_INDENT}{_INDENT}{json.dumps(path)},\n" for path in sorted(set(paths)))
    chunks = [header.rstrip("\n")]
    loads = _load_statements(ordered)
    if loads:
        chunks.append("\n".join(loads))
    chunks.extend(render_target(target) for target in ordered)
    chunks.append(
        "exports_files(\n"
        f"{_INDENT}[\n{exported}{_INDENT}],\n"
        f'{_INDENT}visibility = ["//visibility:public"],\n'
        ")"
    )
    return "\n\n".join(chunks) + "\n"


def render_gazelle_build(config: GazelleConfig, *, header: str = GENERATED_HEADER) -> str:
    """The `# gazelle:` directive preamble written *before* the generator runs (§3.3 step 2).

    Emitted instead of targets — a `uses_gazelle` adapter delegates emission and does not
    pretend to generate targets itself, so this file deliberately declares none.
    """
    lines = [header.rstrip("\n"), ""]
    if config.prefix is not None:
        lines.append(f"# gazelle:prefix {config.prefix}")
    lines += [f"# gazelle:exclude {path}" for path in config.exclude]
    lines += list(config.directives)
    return "\n".join(lines) + "\n"


def coarse_build_targets(
    plan: CoarsePlan,
    rules: Mapping[Ecosystem, str],
    *,
    load_from: Mapping[Ecosystem, str] | None = None,
) -> list[BuildTarget]:
    """§3.1 6e → `BuildTarget`s: **one** library target per `(ecosystem, scc_id)`.

    The union of the members' sources, in one target, is the whole point: 6e is reached because
    the members are mutually dependent, so one target per member reproduces the SCC in the Bazel
    target graph and every repo in the SCC's dependent cone is stranded behind a build that can
    never go green. `CoarseTarget.name` already folds `scc:` to `scc_` — a `:` inside a target
    name does not parse as a label at all.

    `rules` maps an ecosystem to its library rule name. It is a parameter because the rule name
    is adapter knowledge (§7.5) and `bazel/` carries no ecosystem exemption (§13 row 6); the
    driver reads it off the registry and hands it in.
    """
    loads = load_from or {}
    out: list[BuildTarget] = []
    for coarse in sorted(plan.targets, key=lambda t: (t.ecosystem.value, t.scc_id)):
        rule = rules.get(coarse.ecosystem)
        if rule is None:
            raise ValueError(
                f"{coarse.scc_id}: no library rule registered for {coarse.ecosystem.value}; "
                "an ATOMIC_WAVE SCC cannot be coarsened without one (Rule 11: fail loud)"
            )
        out.append(
            BuildTarget(
                package=coarse.package,
                name=coarse.name,
                rule=rule,
                load_from=loads.get(coarse.ecosystem),
                srcs=list(coarse.srcs),
                attrs={"tags": [f"fleet_scc={coarse.scc_id}"]},
            )
        )
    return out


_STUB_FAILING_TARGET_NAME: Final = "stub"
"""The single target `bazel.layout.stub_dest(coord_key)` names — `//<stub_dest>:stub`."""

_STUB_FAILING_OUT: Final = "UNBUILDABLE"
"""Never produced: `cmd` exits before writing it. A real output name is still required —
`genrule` refuses an empty `outs` — and this one names the reason in the label itself."""


def stub_failing_target(*, coord_key: str, provider_repo_id: str, dest: str) -> BuildTarget:
    """§3.5 item 2 — the never-published half of the stub-creation bundle (task-68, Leg 2).

    A single, GENERIC (non-per-ecosystem) `genrule`: it is a Bazel-native rule needing no
    `load()`, so it renders identically whether the abandoned provider was Maven, npm, PyPI,
    crates.io or a Go module — no adapter branch is needed, and §12.6's confinement rule (no raw
    `Ecosystem` check outside `manifests/`/`ecosystems/`/`config/rules/`) would forbid one here
    anyway. This is the shape research-7 §5 flagged as likely and CLAUDE.md's own directive is to
    try the ecosystem-agnostic form first — this one needed no adapter branch to satisfy it.

    `cmd` runs `exit 1` after an `echo` to stderr naming the abandoned provider and its
    coordinate, so the failure is a genuine BUILD-time action failure (SPEC §3.5 item 2: "fails
    at build time with an explicit message, never at runtime silently") — never a green build
    that quietly ships an empty package nothing consumes. `outs` names one file that is never
    produced: `cmd` exits before Bazel ever checks for it, so the actual failure is always the
    exit code and the message, not a missing-output error that would obscure it.
    """
    message = (
        f"fleet: {provider_repo_id} (coordinate {coord_key}) is REQUIRES_HUMAN_INTERVENTION "
        "with no published artifact; this EMPTY_FAILING stub cannot be built. Resolve the "
        "abandoned repo or replace this dependency (SPEC section 3.5 item 2)."
    )
    return BuildTarget(
        package=dest,
        name=_STUB_FAILING_TARGET_NAME,
        rule="genrule",
        attrs={
            "outs": [_STUB_FAILING_OUT],
            "cmd": f"echo {json.dumps(message)} >&2; exit 1",
        },
    )


