_ATOM = re.compile(r"^(==|>=|<=|=|>|<|\^|~>|~)?\s*v?(\d+(?:\.\d+)*)")
"""The same spec grammar `graph/collisions.py` audits with. That module answers the weaker
question — *is the intersection non-empty* — at Phase 1; Phase 3 needs the **selected version**,
which no satisfiability predicate returns. See HONEST_GAPS: a shared `util/semver.py` is the
right home for both, and creating it is outside this change's blast radius."""


def _pad(version: tuple[int, ...], width: int) -> tuple[int, ...]:
    return version + (0,) * (width - len(version))


def _cmp(a: tuple[int, ...], b: tuple[int, ...]) -> int:
    width = max(len(a), len(b))
    left, right = _pad(a, width), _pad(b, width)
    return (left > right) - (left < right)


def _parse_version(text: str) -> tuple[int, ...]:
    return tuple(int(part) for part in text.split("."))


@dataclass(frozen=True, slots=True)
class VersionRange:
    """One requirement as a half-open interval, keeping the version *text* as written.

    The text matters: `bazel_dep(version = ...)` is compared by Bazel's own version parser, and
    rewriting a declared `31` as `31.0.0` is a change to the module graph we did not intend.
    """

    lower: tuple[int, ...] | None = None
    lower_text: str = ""
    lower_inclusive: bool = True
    upper: tuple[int, ...] | None = None
    upper_inclusive: bool = False

    @property
    def is_empty(self) -> bool:
        if self.lower is None or self.upper is None:
            return False
        order = _cmp(self.lower, self.upper)
        if order > 0:
            return True
        return order == 0 and not (self.lower_inclusive and self.upper_inclusive)

    def contains(self, version: tuple[int, ...]) -> bool:
        if self.lower is not None:
            order = _cmp(version, self.lower)
            if order < 0 or (order == 0 and not self.lower_inclusive):
                return False
        if self.upper is not None:
            order = _cmp(version, self.upper)
            if order > 0 or (order == 0 and not self.upper_inclusive):
                return False
        return True

    def intersect(self, other: VersionRange) -> VersionRange:
        lower, lower_text, lower_inclusive = self.lower, self.lower_text, self.lower_inclusive
        if other.lower is not None and (
            lower is None
            or _cmp(other.lower, lower) > 0
            or (_cmp(other.lower, lower) == 0 and not other.lower_inclusive)
        ):
            lower, lower_text, lower_inclusive = (
                other.lower,
                other.lower_text,
                other.lower_inclusive,
            )
        upper, upper_inclusive = self.upper, self.upper_inclusive
        if other.upper is not None and (
            upper is None
            or _cmp(other.upper, upper) < 0
            or (_cmp(other.upper, upper) == 0 and not other.upper_inclusive)
        ):
            upper, upper_inclusive = other.upper, other.upper_inclusive
        return VersionRange(
            lower=lower,
            lower_text=lower_text,
            lower_inclusive=lower_inclusive,
            upper=upper,
            upper_inclusive=upper_inclusive,
        )


def _caret_ceiling(version: tuple[int, ...]) -> tuple[int, ...]:
    major, minor, patch = _pad(version, 3)[:3]
    if major:
        return (major + 1, 0, 0)
    if minor:
        return (0, minor + 1, 0)
    return (0, 0, patch + 1)


def parse_range(spec: str) -> VersionRange | None:
    """One version spec → a `VersionRange`, or `None` when the grammar does not cover it.

    `None` is not "unconstrained": an unparseable spec is *excluded* from the intersection and
    reported, because a `VersionConflict` at `severity='error'` blocks the run and must never
    rest on a parse this module was not sure of.
    """
    atoms = [a.strip() for a in re.split(r"[,\s]+", spec.strip()) if a.strip()]
    if not atoms:
        return None
    out = VersionRange()
    for atom in atoms:
        match = _ATOM.match(atom)
        if match is None:
            return None
        op = match.group(1) or "=="
        text = match.group(2)
        version = _parse_version(text)
        if op in ("==", "="):
            one = VersionRange(version, text, True, version, True)
        elif op == ">=":
            one = VersionRange(version, text, True)
        elif op == ">":
            one = VersionRange(version, text, False)
        elif op == "<=":
            one = VersionRange(upper=version, upper_inclusive=True)
        elif op == "<":
            one = VersionRange(upper=version)
        elif op == "^":
            one = VersionRange(version, text, True, _caret_ceiling(version), False)
        else:  # `~` / `~>`: pin the minor
            major, minor = _pad(version, 2)[:2]
            one = VersionRange(version, text, True, (major, minor + 1, 0), False)
        out = out.intersect(one)
    return out


class VersionConflict(Exception):
    """An external coordinate whose specs have an **empty intersection** (§13 row 17).

    Always `severity='error'`: there is no version that honours every declared bound, so any pin
    breaks a promise some repo made, and choosing which promise to break is not a decision this
    module is entitled to make silently. This is the one — and only — gate to the
    `conflict_resolution` LLM role.
    """

    severity: Final[Literal["error"]] = "error"

    def __init__(
        self, coord_key: str, specs: Sequence[str], repo_ids: Sequence[str], reason: str
    ) -> None:
        self.coord_key = coord_key
        self.specs = tuple(specs)
        self.repo_ids = tuple(repo_ids)
        self.reason = reason
        super().__init__(
            f"{coord_key}: {reason}; specs={list(self.specs)} from repos={list(self.repo_ids)}"
        )

    def as_finding(self) -> GraphFinding:
        """The `findings` row (§6, kind `VersionConflict`) this conflict is recorded as."""
        return GraphFinding(
            kind="VersionConflict",
            severity="error",
            payload={
                "coord_key": self.coord_key,
                "specs": ", ".join(self.specs),
                "repo_ids": ", ".join(self.repo_ids),
                "reason": self.reason,
            },
        )


def _grouped(requirements: Iterable[VersionRequirement]) -> dict[str, list[VersionRequirement]]:
    out: dict[str, list[VersionRequirement]] = {}
    for req in sorted(requirements, key=lambda r: (r.coord_key, r.repo_id, r.version_spec)):
        out.setdefault(req.coord_key, []).append(req)
    return out


def mvs_select(coord_key: str, requirements: Sequence[VersionRequirement]) -> str:
    """The **minimum version satisfying every spec** — Bazel's MVS, over one coordinate.

    MVS is the maximum of the declared lower bounds, which is the smallest version that can
    satisfy them all; it is then checked against every declared upper bound. A version that
    satisfies *most* specs is never selected, however large that majority: 30 repos pinned
    `[31, 32)` do not lose a vote to 31 repos pinned `[33, 34)`, they produce a conflict.
    """
    reqs = [r for r in requirements if r.coord_key == coord_key]
    if not reqs:
        raise ValueError(f"{coord_key}: no requirements to select from")
    specs = sorted({r.version_spec for r in reqs})
    repo_ids = sorted({r.repo_id for r in reqs})

    parsed: list[tuple[str, VersionRange]] = []
    for spec in specs:
        rng = parse_range(spec)
        if rng is not None:
            parsed.append((spec, rng))
    if not parsed:
        raise VersionConflict(coord_key, specs, repo_ids, "no spec could be parsed")

    combined = VersionRange()
    for _spec, rng in parsed:
        combined = combined.intersect(rng)
    if combined.is_empty:
        raise VersionConflict(
            coord_key, specs, repo_ids, "the specs' intersection is empty (no version satisfies "
            "every declared bound)"
        )

    # Candidates are the versions actually declared as lower bounds — the values that reach
    # `bazel_dep(version = …)`. MVS picks the smallest of them that satisfies every spec, which
    # is `combined.lower` whenever that bound is inclusive.
    candidates = sorted(
        {(rng.lower, rng.lower_text) for _s, rng in parsed if rng.lower is not None}
    )
    for version, text in candidates:
        if combined.contains(version) and all(rng.contains(version) for _s, rng in parsed):
            return text
    raise VersionConflict(
        coord_key,
        specs,
        repo_ids,
        "no declared version satisfies every spec (an exclusive or absent lower bound leaves "
        "MVS nothing to select; a pin must be declared explicitly)",
    )


@dataclass(frozen=True, slots=True)
class VersionResolution:
    """MVS's verdict over the whole external surface of a wave."""

    selected: Mapping[str, str] = field(default_factory=dict)
    conflicts: tuple[VersionConflict, ...] = ()

    @property
    def findings(self) -> tuple[GraphFinding, ...]:
        return tuple(c.as_finding() for c in self.conflicts)

    @property
    def ok(self) -> bool:
        return not self.conflicts

    def require_resolved(self) -> Mapping[str, str]:
        """Rule 11: the first unresolved conflict is raised rather than rendered around."""
        if self.conflicts:
            raise self.conflicts[0]
        return self.selected


def reconcile_versions(requirements: Sequence[VersionRequirement]) -> VersionResolution:
    """§3.3 step 3 over every coordinate at once, collecting conflicts instead of stopping.

    Collected, not raised, because one unsatisfiable coordinate must not hide the other four in
    the same wave — the operator wants the whole list before invoking `conflict_resolution`.
    `require_resolved()` is the fail-loud edge for callers that must not proceed.
    """
    selected: dict[str, str] = {}
    conflicts: list[VersionConflict] = []
    for coord_key, reqs in sorted(_grouped(requirements).items()):
        try:
            selected[coord_key] = mvs_select(coord_key, reqs)
        except VersionConflict as conflict:
            conflicts.append(conflict)
    return VersionResolution(selected=selected, conflicts=tuple(conflicts))


@runtime_checkable
class OverrideProposal(Protocol):
    """The `conflict_resolution` role's output, structurally (`VersionConflictResolution`, §7.7).

    A `Protocol` so this module does not import the LLM package to validate the LLM: the
    validator is the thing that must keep working when the model is wrong.
    """

    @property
    def coord_key(self) -> str: ...
    @property
    def proposed_version(self) -> str: ...
    @property
    def mechanism(self) -> str: ...
    @property
    def violated_specs(self) -> tuple[str, ...]: ...


@dataclass(frozen=True, slots=True)
class OverrideDecision:
    """Code's verdict on a model's pin. `accepted` is the only thing a caller may act on."""

    accepted: bool
    coord_key: str
    version: str
    mechanism: str
    violated: tuple[str, ...] = ()
    """Specs this pin actually breaks — recomputed here, never read from the proposal."""
    undisclosed: tuple[str, ...] = ()
    """Violations the model did not declare. Non-empty ⇒ rejected: a pin whose damage is
    understated reaches a reviewer as safe."""
    reason: str = ""


def validate_override(
    proposal: OverrideProposal, requirements: Sequence[VersionRequirement]
) -> OverrideDecision:
    """Re-derive the proposal's consequences against **every** contributing spec (§7.7).

    On an empty intersection every pin violates something, so "violates a spec" cannot itself be
    the rejection rule — the rule is *disclosure*: the specs the pin breaks are recomputed here
    and compared with `violated_specs`. Anything the model failed to declare rejects the
    proposal. Also rejected: a mechanism outside the two constructs `render_module_bazel` can
    emit, a version that does not parse, and a pin for a coordinate nobody asked about — each of
    which would otherwise be written into `MODULE.bazel` verbatim.
    """
    reqs = [r for r in requirements if r.coord_key == proposal.coord_key]
    if not reqs:
        return OverrideDecision(
            False, proposal.coord_key, proposal.proposed_version, proposal.mechanism,
            reason="no requirement names this coordinate; the pin has no contributing specs",
        )
    if proposal.mechanism not in OVERRIDE_MECHANISMS:
        return OverrideDecision(
            False, proposal.coord_key, proposal.proposed_version, proposal.mechanism,
            reason=f"mechanism must be one of {sorted(OVERRIDE_MECHANISMS)}",
        )
    parsed_pin = parse_range(proposal.proposed_version)
    if parsed_pin is None or parsed_pin.lower is None:
        return OverrideDecision(
            False, proposal.coord_key, proposal.proposed_version, proposal.mechanism,
            reason="proposed_version is not an exact version this module can render",
        )
    pin = parsed_pin.lower

    violated: list[str] = []
    unparsed: list[str] = []
    for spec in sorted({r.version_spec for r in reqs}):
        rng = parse_range(spec)
        if rng is None:
            unparsed.append(spec)
        elif not rng.contains(pin):
            violated.append(spec)
    if unparsed:
        return OverrideDecision(
            False, proposal.coord_key, proposal.proposed_version, proposal.mechanism,
            violated=tuple(violated),
            reason=f"cannot verify the pin against unparseable specs {unparsed}",
        )
    undisclosed = tuple(sorted(set(violated) - set(proposal.violated_specs)))
    if undisclosed:
        return OverrideDecision(
            False, proposal.coord_key, proposal.proposed_version, proposal.mechanism,
            violated=tuple(violated), undisclosed=undisclosed,
            reason="the pin violates specs the proposal did not disclose",
        )
    return OverrideDecision(
        True, proposal.coord_key, proposal.proposed_version, proposal.mechanism,
        violated=tuple(violated),
        reason="every violated spec was disclosed" if violated else "satisfies every spec",
    )


def resolve_workspace_deps(
    deps: Sequence[WorkspaceDep], selected: Mapping[str, str]
) -> tuple[WorkspaceDep, ...]:
    """Stamp MVS's winner onto each `WorkspaceDep.resolved_version` (§5.6)."""
    out: list[WorkspaceDep] = []
    for dep in deps:
        version = selected.get(dep.coordinate.key)
        out.append(dep if version is None else dep.model_copy(update={"resolved_version": version}))
    return tuple(out)


