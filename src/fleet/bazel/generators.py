def _split_extension(extension: str) -> tuple[str, str]:
    """`maven.install` → (`maven`, `install`). The proxy variable and the tag class."""
    var, _, tag = extension.partition(".")
    if not var or not tag:
        raise ValueError(
            f"extension id {extension!r} must be '<extension>.<tag_class>' (e.g. maven.install)"
        )
    return var, tag


def _registry_extension_bzls() -> Mapping[str, str]:
    """The adapters' `use_extension` label table, imported at CALL time.

    Imported here rather than at module import so `bazel/` keeps no import-time dependency on the
    adapter registry, and so this module stays testable with an injected map. It is a *lookup of
    adapter-declared data*, not language knowledge: no `Ecosystem` member, no rule name and no
    directory is named in this file, which is what §13 row 6 forbids.

    The alternative — the drivers threading a map down to every call — is what the
    `@<ruleset>//:extensions.bzl` guess was standing in for: no caller in `src/` ever passed one,
    so the guess was what shipped, and it names a file that exists in one of the seven rulesets.
    """
    from fleet.ecosystems import extension_bzls

    return extension_bzls()


def _registry_ruleset_repo_names() -> dict[str, str]:
    """The adapters' module-name → apparent-repo-name table, imported at CALL time.

    Same shape and same reason as `_registry_extension_bzls` above: which name a ruleset asks its
    dependents to spell it with is per-ruleset knowledge that §13 row 6 keeps out of `bazel/`,
    and an injected map keeps this module testable without the registry.
    """
    from fleet.ecosystems import ruleset_repo_names

    return ruleset_repo_names()


def _load_repo(label: str) -> str | None:
    """The apparent repo a `load()` label reads from: `@aspect_rules_js//js:defs.bzl` →
    `aspect_rules_js`. `None` for a label that names no repo at all.

    A package-relative `//tools:defs.bzl` and a same-repo `:defs.bzl` name the main repository,
    which needs no `bazel_dep`; `@@rules_python+//…` is the canonical form and folds to the same
    name as its apparent one for our purposes, which is why both `@` prefixes are stripped.
    """
    if not label.startswith("@"):
        return None
    return label.lstrip("@").partition("//")[0] or None


def _tag_attrs(
    attrs: Mapping[str, str | list[str]], fallback: Mapping[str, str]
) -> dict[str, str | int | bool | list[str]]:
    """An adapter's `attrs` are the dialect and are rendered verbatim; the fallback is used only
    when the adapter declared none, so no ecosystem-specific attribute name is invented here."""
    if attrs:
        return dict(attrs)
    return dict(fallback)


def _bazel_dep(module: str, version: str, repo_name: str | None) -> str:
    """One `bazel_dep` line, carrying `repo_name` only where the apparent name differs.

    The apparent name is what every `load()` of that ruleset must spell, and a module is visible
    under its MODULE name unless the dependent says otherwise — so this argument is the only
    thing standing between a generator that writes `@io_bazel_rules_go` and a root module that
    knows the repo as `@rules_go`.
    """
    line = f"bazel_dep(name = {_render_scalar(module)}, version = {_render_scalar(version)}"
    if repo_name is not None and repo_name != module:
        line += f", repo_name = {_render_scalar(repo_name)}"
    return line + ")"


def render_module_bazel(
    workspace_deps: Sequence[WorkspaceDep],
    *,
    module_name: str,
    ruleset_versions: Mapping[str, str],
    module_version: str = "0.0.0",
    toolchains: Sequence[ToolchainRequirement] = (),
    targets: Sequence[BuildTarget] = (),
    single_version_overrides: Mapping[str, str] | None = None,
    extension_bzl: Mapping[str, str] | None = None,
    ruleset_repo_names: Mapping[str, str] | None = None,
    header: str = GENERATED_HEADER,
) -> str:
    """The whole `MODULE.bazel`: one `bazel_dep` per ruleset, one tag call per dep (§3.3 step 3).

    Every requirement is recorded, and Bazel's MVS does the selecting for the *artifacts* — which
    is why there is no "pick a winner" branch here. `single_version_overrides` carries the
    *validated* output of `validate_override` and nothing else: an unvalidated pin has no path
    into this function. A ruleset with no pinned version in `build.ruleset_versions` (§9) is a
    hard error, because an unpinned `bazel_dep` resolves differently on the next run.

    **The rulesets are PINNED, and the pin is `single_version_override` (§9).** `bazel_dep(version
    = X)` is an MVS *lower bound*, not a pin: real Bazel selected `rules_python@1.7.0` for a
    configured `1.0.0`, because a transitive module in BCR declared a higher floor. §9's
    reproducibility guarantee is that two runs of the same fleet build the same bytes, and a floor
    that any unrelated BCR publication can raise does not provide it — the monorepo's Python rules
    would change under the fleet with no diff anywhere in this repository. So every ruleset the
    adapters name gets `single_version_override(module_name = …, version = …)` beside its
    `bazel_dep`, and `build.ruleset_versions` means what its name and its docs say.

    A validated conflict-resolution override for the same module name WINS over the configured
    pin: it went through `validate_override` against every contributing spec, and emitting both
    would be a duplicate `single_version_override`, which Bazel rejects outright.

    `extension_bzl` maps a `use_extension` proxy name to the `.bzl` label its ruleset ships it in.
    Default `None` reads the adapters' own table; a var that neither the caller nor the registry
    can place raises, because the alternative is a plausible-looking label that dies inside
    Bazel's loader with a message that points at the ruleset instead of at us (Rule 11).

    **`targets` is what a `load()` needs, and a dependency nobody declared is still a dependency.**
    The ruleset set was once `{d.ruleset for d in workspace_deps} | {t.ruleset for t in toolchains}`
    — the rulesets someone *declared*. A repo whose only claim on a ruleset is that one of its
    targets loads a rule out of it (a package with no external npm coordinates and a `js_binary`
    loading `@aspect_rules_js//js:defs.bzl`) got no `bazel_dep` at all, and real Bazel answered
    `Unable to find package for @@[unknown repo 'aspect_rules_js' …]//js:defs.bzl`. So the
    targets' `load_from` labels contribute too.

    A load-derived name is admitted **only when `ruleset_versions` pins it**, and that is not
    laziness about the missing-pin error: a load label carries an *apparent repo* name, which is
    not a module name. `rules_go` publishes itself as `@io_bazel_rules_go` and `rules_java` is
    injected by Bazel itself, so `bazel_dep(name = "io_bazel_rules_go")` names nothing in any
    registry and raising on it would break every Go repo in the fleet. The pin is the operator's
    statement that a name *is* one of this monorepo's rulesets; declared rulesets still hard-error
    when unpinned, because there the adapter told us it is a module. A pinned ruleset that nothing
    depends on is still not emitted — `bazel_dep` follows use, never the configuration table.

    **`ruleset_repo_names` is the other half of that same split, and it is what makes the apparent
    name TRUE instead of merely tolerated.** Knowing that `@io_bazel_rules_go` is not a module
    name kept a bogus `bazel_dep` out of the file; it did not put the repo in scope, and nothing
    else did either — so every Go package the delegated generator wrote, each loading
    `@io_bazel_rules_go//go:def.bzl`, failed to LOAD under real Bazel (`No repository visible as
    '@io_bazel_rules_go' from main repository`), for the whole ecosystem at once. A module's
    apparent name is set by the DEPENDENT's `bazel_dep(repo_name = …)` and by nothing the module
    itself declares, so it is emitted here, from the adapters' own table (`None` reads the
    registry, as `extension_bzl` does). Only where the two names differ: `repo_name` equal to the
    module name is noise, and every other ruleset in the table is spelled as it is published.
    """
    overrides = dict(single_version_overrides or {})
    bzl_for = dict(_registry_extension_bzls() if extension_bzl is None else extension_bzl)
    repo_name_for = dict(
        _registry_ruleset_repo_names() if ruleset_repo_names is None else ruleset_repo_names
    )

    declared = {d.ruleset for d in workspace_deps} | {t.ruleset for t in toolchains}
    loaded = {
        repo
        for target in targets
        if target.load_from is not None
        for repo in (_load_repo(target.load_from),)
        if repo is not None
    }
    rulesets = sorted(declared | (loaded & set(ruleset_versions)))
    missing = [r for r in sorted(declared) if r not in ruleset_versions]
    if missing:
        raise ValueError(
            f"build.ruleset_versions pins no version for {missing}; an unpinned bazel_dep is a "
            "build that resolves differently on the next run (§9)"
        )
    unresolved = sorted(
        {d.coordinate.key for d in workspace_deps if d.resolved_version is None and not d.attrs}
    )
    if unresolved:
        raise ValueError(
            f"{unresolved} reached MODULE.bazel rendering with no resolved_version; §3.3 step 3 "
            "reconciliation must run first (Rule 11: fail loud)"
        )

    chunks: list[str] = [header.rstrip("\n")]
    chunks.append(
        "module(\n"
        f"{_INDENT}name = {_render_scalar(module_name)},\n"
        f"{_INDENT}version = {_render_scalar(module_version)},\n"
        ")"
    )
    chunks.append(
        "\n".join(_bazel_dep(r, ruleset_versions[r], repo_name_for.get(r)) for r in rulesets)
        if rulesets
        else ""
    )
    pins = {r: ruleset_versions[r] for r in rulesets} | overrides
    if pins:
        chunks.append(
            "\n".join(
                f"single_version_override(module_name = {_render_scalar(name)}, "
                f"version = {_render_scalar(pins[name])})"
                for name in sorted(pins)
            )
        )

    grouped: dict[tuple[str, str], list[str]] = {}
    repos: dict[str, set[str]] = {}
    for dep in sorted(workspace_deps, key=lambda d: (d.ruleset, d.extension, d.coordinate.key)):
        var, tag = _split_extension(dep.extension)
        attrs = _tag_attrs(
            dep.attrs,
            {"name": dep.coordinate.name, "version": dep.resolved_version or ""},
        )
        lines = [f"{var}.{tag}("]
        for key in sorted(attrs):
            lines += _render_attr(key, attrs[key])
        lines.append(")")
        grouped.setdefault((dep.ruleset, var), []).append("\n".join(lines))
        repos.setdefault(var, set()).add(dep.repo_name)
    for toolchain in sorted(toolchains, key=lambda t: (t.ruleset, t.extension, t.name)):
        var, tag = _split_extension(toolchain.extension)
        attrs = _tag_attrs(
            dict(toolchain.attrs), {"name": toolchain.name, "version": toolchain.version}
        )
        lines = [f"{var}.{tag}("]
        for key in sorted(attrs):
            lines += _render_attr(key, attrs[key])
        lines.append(")")
        grouped.setdefault((toolchain.ruleset, var), []).append("\n".join(lines))
        # A tag call CREATES repos; `use_repo` is what makes them visible to the root module, and
        # nothing else does. Without it `@npm_typescript` is `no such package '@@[unknown repo
        # 'npm_typescript' requested from @@]//'` — the same import the `workspace_deps` loop above
        # has always emitted, for the half of MODULE.bazel that never had it.
        repos.setdefault(var, set()).update(toolchain.repo_names)

    for ruleset, var in sorted(grouped):
        bzl = bzl_for.get(var)
        if bzl is None:
            raise ValueError(
                f"{ruleset}: no .bzl label is registered for the module extension {var!r}; the "
                f"adapter that names it must declare it in `extension_bzl` (Rule 11: a guessed "
                f"label fails inside Bazel's loader, pointing at the ruleset instead of at us)"
            )
        block = [f"{var} = use_extension({_render_scalar(bzl)}, {_render_scalar(var)})"]
        block += sorted(set(grouped[(ruleset, var)]))
        for repo_name in sorted(repos.get(var, set())):
            block.append(f"use_repo({var}, {_render_scalar(repo_name)})")
        chunks.append("\n".join(block))

    return "\n\n".join(chunk for chunk in chunks if chunk) + "\n"
