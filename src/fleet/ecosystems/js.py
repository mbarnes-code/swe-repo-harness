def _npm_package_name(coordinate: Coordinate) -> str:
    """`(@acme, ui)` → `@acme/ui`; `("", left-pad)` → `left-pad`.

    The registry name, reassembled from the scope `manifests/npm.py` split off. It is what the
    lockfile keys on and what `npm_link_all_packages()` names its link after, so this is the ONE
    spelling that has to survive the round trip through `Coordinate`.
    """
    return f"{coordinate.group}/{coordinate.name}" if coordinate.group else coordinate.name


def _needs_npm_hub(unit: BuildUnit) -> bool:
    """Whether this unit references the `@npm` hub at all — the ONE gate for every part of it.

    True for a unit with an external dependency (it has a registry package to link) and for one
    with a linkable sibling (it has a `link:` entry to link), because those are the two kinds of
    row that end up in the same lockfile and are materialized by the same
    `npm_link_all_packages()`. Spelled once and read by `workspace_deps`, `workspace_files`,
    `root_targets` and `resolution`, because a unit that emits the `npm_translate_lock` tag but
    no lockfile — or a lockfile but no macro at the root — fails inside the ruleset with a
    message about our file.
    """
    return bool(unit.external_coordinates or _first_party(unit))


def _first_party(unit: BuildUnit) -> list[InternalDep]:
    """The unit's sibling repos that can be linked as npm packages, ordered by `dest`.

    "Can be" is `published is not None`: `npm_translate_lock` links a first-party package under
    its **registry name**, and a sibling that publishes no coordinate has none. Such a sibling is
    not dropped — the driver's plain `//<dest>:<name>` label is still in `dep_labels()` — it
    simply cannot become a `node_modules` entry, which is the honest outcome rather than a link
    named after a directory.
    """
    return sorted(
        (dep for dep in unit.internal_deps if dep.published is not None), key=lambda d: d.dest
    )


def _all_first_party(units: Sequence[BuildUnit]) -> list[InternalDep]:
    """Every linkable sibling of every contributing unit, deduped by `dest` and ordered by it.

    The union half of `_first_party`, for the resolve that runs once per ecosystem: two repos in
    the fleet may link the same sibling, and the root manifest holds ONE `link:` entry per
    package while the resolver's scratch tree holds ONE manifest per directory. `dest` is the
    identity for both, so it is the dedupe key here — stripped, because that is the form both the
    `link:` specifier and the sibling's input **path** are spelled in, and two entries for one
    path is a file staged twice.

    Ordered by the same `dest` `_first_party` sorts on, and the tie-break is total (`label`, then
    the published coordinate) so the winner for a repeated `dest` does not depend on which unit
    the caller listed first — §11.6 requires the same plan to render the same bytes, and the units
    reach this method in whatever order the driver grouped them.
    """
    ordered = sorted(
        (dep for unit in units for dep in _first_party(unit)),
        key=lambda d: (
            d.dest,
            d.label,
            d.published.key if d.published is not None else "",
            (d.published.version_spec or "") if d.published is not None else "",
        ),
    )
    deduped: dict[str, InternalDep] = {}
    for dep in ordered:
        deduped.setdefault(dep.dest.strip("/"), dep)
    return list(deduped.values())


def _importer_dests(units: Sequence[BuildUnit]) -> list[str]:
    """Every pnpm *importer* directory this fleet's JS units imply, deduped and sorted.

    Two kinds of directory, one list, because both hold a `package.json` the resolver reads and
    both therefore owe a `packages:` entry and a `.bazelignore` line (ADR-0048):

    * each unit that references the `@npm` hub at all, which is the repo whose own dependencies
      the importer records — this is the half that stops `[app ms@^2.0.0, report ms@^2.1.3]` from
      collapsing to one specifier;
    * each **linkable sibling**, because pnpm resolves a `link:` specifier by reading the
      manifest at that directory and a directory holding a manifest inside the workspace is an
      importer whether or not the sibling declared a dependency of its own.

    A unit that references the hub in neither way is deliberately absent: it contributes no
    manifest, so listing it would point `packages:` at a directory with nothing in it.
    """
    dests = {unit.dest.strip("/") for unit in units if _needs_npm_hub(unit)}
    dests |= {dep.dest.strip("/") for dep in _all_first_party(units)}
    return sorted(dests)


def _link_specifier(importer_dest: str, sibling_dest: str) -> str:
    """The `link:` specifier an importer at `importer_dest` must write for `sibling_dest`.

    **Importer-relative, and that is measured, not assumed.** pnpm resolves `link:` against the
    directory of the manifest that declares it. Handed `{"@acme/lib": "link:ts/acme/lib"}` in
    `ts/acme/app/package.json`, real pnpm 10.16.1 answers `WARN Installing a dependency from a
    non-existent directory: …/ts/acme/app/ts/acme/lib` and writes a lock whose
    `version: link:ts/acme/lib` rules_js then reads as `paths.normalize(paths.join(import_path,
    link))` = `ts/acme/app/ts/acme/lib` (`npm/private/pnpm.bzl`'s
    `_convert_pnpm_v9_importer_dependency_map`) — a Bazel package that does not exist. The
    root-relative spelling was correct only while the root was the ONE importer.

    `link:../../../ts/acme/lib` and `workspace:*` were both measured to record the identical
    `version: link:../lib`, so the protocol choice is free and ADR-0046's `link:` stands.
    """
    return f"link:{posixpath.relpath(sibling_dest, importer_dest)}"


def _sibling_package_json(dep: InternalDep) -> str:
    """The floor manifest for a linkable sibling that shipped no `package.json` of its own.

    Named after the sibling's published coordinate and not after its directory: pnpm records the
    link under the name it reads out of the manifest, and `npm_link_all_packages()` then creates
    `node_modules/<that name>` — so a floor named `lib` would link `@acme/lib` under `lib` and
    the consumer's `import … from '@acme/lib'` would still not resolve.
    """
    coordinate = dep.published
    payload = {
        "name": _npm_package_name(coordinate) if coordinate is not None else dep.dest,
        "version": (coordinate.version_spec if coordinate else None) or "0.0.0",
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def _root_package_json() -> str:
    """The pnpm **workspace root** manifest: a name, a version, `private`, and NO dependencies.

    The root is an importer like any other, and the one thing it must not be is the fleet's
    dependency dumping ground. The flat map this replaces was keyed on package name and unioned
    over every unit, so it *overwrote in place*: `[app ms@^2.0.0, report ms@^2.1.3]` emitted
    `{"ms": "^2.1.3"}` and `^2.0.0` was gone with no error, the surviving specifier being nothing
    more meaningful than the lexicographically largest (ADR-0048). Each repo's declarations now
    live in that repo's own `<dest>/package.json`, which is the only place they can be kept
    apart.

    `private` because a workspace root is never published, and it is what stops pnpm warning
    about a root manifest with no `license`/`repository`.
    """
    payload = {"name": "monorepo", "version": "0.0.0", "private": True}
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def _unit_package_json(unit: BuildUnit) -> str:
    """ONE JS repo's importer manifest: **its own** registry dependencies and **its own** links.

    This is the file that preserves what the flat union destroyed. pnpm records
    `specifier:` verbatim per importer — three importers declaring `ms@^2.0.0`, `ms@^2.1.3` and
    an exact `ms@2.0.0` were measured to keep all three, with `2.0.0` and `2.1.3` coexisting in
    `packages:` under distinct integrity hashes (ADR-0048). An honest limit stated with it: pnpm
    still dedupes *within* a satisfiable range, so `^2.0.0` beside `^2.1.3` resolves to `2.1.3`.
    What multi-importer buys is that no repo's declaration is silently overwritten by another's,
    not that every repo gets its own resolved version.

    The external half is synthesized rather than carried, and that is not a shortcut: the repo's
    own `package.json` names its siblings with registry specifiers (`"@acme/lib": "^1.4.0"`),
    which resolve to nothing on npm — pnpm would fail, or worse, find an unrelated public package
    of that name.

    The first-party half is D12's fix and is the whole of "how one TypeScript package in this
    monorepo imports another": each sibling is declared with pnpm's **`link:` protocol**, so the
    resolved lock carries `'@acme/lib': {specifier: link:../lib, version: link:../lib}` in THIS
    repo's importer. `npm_translate_lock` reads that entry, generates a first-party package store
    whose `src` is `//ts/acme/lib:pkg`, and this repo's own `npm_link_all_packages()`
    materializes it at `//<dest>:node_modules/@acme/lib` — so `tsc` resolves
    `import … from '@acme/lib'` by walking `node_modules`, exactly as it would outside Bazel.
    Without the entry the specifier resolves to nothing and the consumer fails with
    `error TS2307: Cannot find module '@acme/lib'`.

    The manifest's `name` is the repo's **published** registry name where it has one, because a
    sibling links under the name pnpm reads out of the manifest at the linked directory; the
    sanitized target name is the floor for a unit that publishes nothing, since a `dest` with
    slashes in it is not a legal npm name at all.

    Sorted keys and a trailing newline because this text is an input to a lockfile that is
    committed onto the integration branch: two runs must produce the same bytes (§11.6).
    """
    dest = unit.dest.strip("/")
    published = unit.published
    dependencies = {
        _npm_package_name(coordinate): coordinate.version_spec or "*"
        for coordinate in sorted(
            unit.external_coordinates, key=lambda c: (c.key, c.version_spec or "")
        )
    }
    dependencies.update(
        {
            _npm_package_name(dep.published): _link_specifier(dest, dep.dest.strip("/"))
            for dep in _first_party(unit)
            if dep.published is not None
        }
    )
    payload = {
        "name": _npm_package_name(published) if published is not None else target_name(unit),
        "version": (published.version_spec if published is not None else None) or "0.0.0",
        "private": True,
        "dependencies": dict(sorted(dependencies.items())),
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def _pnpm_workspace_text(importers: Sequence[str]) -> str:
    """`pnpm-workspace.yaml`: one `packages:` entry per importer, plus the build allowlist.

    The `packages:` list is what MAKES the importers importers — pnpm resolves a workspace, and a
    directory holding a `package.json` that no member glob covers is a directory pnpm never
    reads. It is spelled as explicit paths and not as a glob so the file states exactly the set
    `_importer_dests` computed: a glob would silently pick up a directory some later phase
    creates, and the `.bazelignore` lines beside it would then be one short.

    `allowBuilds: {}` is unchanged and keeps its own reason. `npm_translate_lock` REFUSES to
    evaluate without an explicit build-allowlist: "pnpm 'allowBuilds' (or 'onlyBuiltDependencies'
    in pnpm < 10.26) configuration required". It is a mapping and not a list — a list gets
    `'list' value has no field or method 'items'` from `npm_translate_lock_state.bzl` — and `{}`
    is the honest value: *no* package may run a lifecycle hook in this monorepo until someone
    decides otherwise, which is also the safe default for code being migrated. The file is not
    NAMED by any tag, so nothing in the module text points at it; it is required by the ruleset
    all the same, which is precisely why the knowledge lives on the adapter that names the
    extension rather than anywhere a generic file-reference walk could find it (§13 row 6).
    """
    listed = (
        "packages: []\n"
        if not importers
        else "packages:\n" + "".join(f"  - {dest}\n" for dest in importers)
    )
    return (
        "# GENERATED BY fleet — the monorepo's pnpm workspace: one package per JS importer.\n"
        f"{listed}"
        "allowBuilds: {}\n"
    )


def _bazelignore_text(importers: Sequence[str]) -> str:
    """`.bazelignore`: the root `node_modules` **and one `<dest>/node_modules` line per importer**.

    Mandatory, and read off the ruleset rather than reasoned about:
    `npm_translate_lock_helpers.bzl`'s `_find_missing_bazel_ignores` computes
    `paths.normalize(paths.join(root_package, importer, "node_modules"))` for **every** importer
    path and fails the repository rule for each one it cannot find. A bare `node_modules` line
    does NOT cover `ts/acme/app/node_modules`: the check is an exact string match against the
    normalized lines, so the file owes one line per importer the moment the lock has more than
    the root one.
    """
    lines = ["node_modules", *(f"{dest}/node_modules" for dest in importers)]
    return "".join(f"{line}\n" for line in lines)

