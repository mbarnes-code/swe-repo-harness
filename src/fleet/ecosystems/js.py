_NPM_PACKAGE_TARGET: Final = "pkg"
"""The name `npm_translate_lock` expects a first-party package's target to have.

Not a convention this harness chose: `npm_translate_lock.npm_package_target_name` defaults to
`"pkg"`, and the generated store is `_npm_local_package_store(src = "//<dir>:pkg", …)` for a
`link:<dir>` entry. Get the name wrong and Bazel reports `no such target '//ts/acme/lib:pkg'`
from a file nobody in this repository wrote."""

_NODE_MODULES_TARGET: Final = "node_modules"
"""The name `npm_link_all_packages()` is given — in the ROOT package **and in every importer's
own package** — and therefore the second segment of every external label this adapter emits:
`//<dest>:node_modules/<pkg>`.

`@npm//:<pkg>` — what the base class's maven-shaped `@<repo>//:<name>` produced — names nothing.
The `npm_translate_lock` hub's own root package declares `noop`, `sync` and
`exports_files(["defs.bzl"])` and no packages at all; the *importable* targets are the links
`npm_link_all_packages()` creates, and it creates them **per pnpm importer**: with one importer
per JS repo (ADR-0048) the link a `ts/acme/app` target depends on is declared in `ts/acme/app`
and is `//ts/acme/app:node_modules/left-pad`. Real Bazel's answer to the `@npm//:left-pad`
spelling was "no such target '@@aspect_rules_js++npm+npm//:left-pad': target 'left-pad' not
declared in package ''"; its answer to a root-package spelling of a per-importer link is the
same message about `package ''`."""

_PNPM_LOCK: Final = f"//:{_PNPM_LOCK_FILE}"
"""ONE lockfile at the monorepo root, not one per package: `npm_translate_lock` builds a single
`@npm` repository for the whole workspace, and a second lock would give two packages two
different resolutions of the same dependency with no MVS step to notice. One *file* is not one
*importer* — the file this names is a pnpm **workspace** lock carrying one `importers:` entry
per JS repo (ADR-0048), which is how two repos keep two different specifiers inside one lock.

The label and the file are spelled from ONE constant (D10). They were two independent strings in
two phases that never spoke, and the phase that names the file was not the phase that would have
had to create it — so nothing created it, and real Bazel failed inside `npm_translate_lock`."""

_BAZELIGNORE: Final = f"//:{_BAZELIGNORE_FILE}"
